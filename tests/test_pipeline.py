TEMPLATES = ['attached', 'combined', 'exported']


def _fit(steps: list) -> SklearnPipeline:
    x, y = load_iris(return_X_y=True)
    return SklearnPipeline(steps).fit(x, y)


@pytest.fixture(scope='module')
def fitted_pipeline() -> SklearnPipeline:
    return _fit(
        [
            ('scaler', StandardScaler()),
            ('skipped', None),
            ('scaler2', StandardScaler(with_mean=False)),
            ('tree', DecisionTreeClassifier(random_state=0)),
        ]
    )


def test_pipeline(fitted_pipeline: SklearnPipeline):
    est = Pipeline(fitted_pipeline)
    assert est.estimator is fitted_pipeline
    # The skipped step isn't ported:
    assert [type(step) for step in est.steps] == [
        Transformer,
        Transformer,
        Estimator,
    ]
    assert est.steps[0].estimator is fitted_pipeline[0]
    assert est.steps[1].estimator is fitted_pipeline[2]
    assert est.steps[2].estimator is fitted_pipeline[-1]
    # The defaults of the final estimator:
    assert est.language == 'java'
    assert est.template == 'attached'
    assert est.class_name == 'Pipeline'
    assert {step.language for step in est.steps} == {'java'}
    assert 'pipeline\n--------\nname: Pipeline(StandardScaler, ' in repr(est)


def test_settings_of_all_steps(fitted_pipeline: SklearnPipeline):
    est = Pipeline(fitted_pipeline, language='go', template='exported')
    assert {step.language for step in est.steps} == {'go'}
    assert {step.template for step in est.steps} == {'exported'}
    est.language = 'php'
    est.template = 'combined'
    est.converter = repr
    assert {step.language for step in est.steps} == {'php'}
    assert {step.template for step in est.steps} == {'combined'}
    assert {step.converter for step in est.steps} == {repr}


@pytest.mark.parametrize('template', TEMPLATES)
@pytest.mark.parametrize('language', LANGUAGES)
def test_port(fitted_pipeline: SklearnPipeline, language: str, template: str):
    """The pipeline is ported to one source file: the ported final estimator
    with the classes of the ported transformers."""
    est = Pipeline(fitted_pipeline, language=language, template=template)
    out = est.port()
    if template == 'exported':
        out, data = out
        # The model data of the final estimator and of each transformer:
        data = json.loads(data)
        assert data['lefts']
        assert data['transformers'] == [
            dict(
                mean=np.asarray(scaler.mean_ if scaler.with_mean else [0] * 4)
                .astype(float)
                .tolist(),
                scale=np.asarray(scaler.scale_).tolist(),
            )
            for scaler in (fitted_pipeline[0], fitted_pipeline[2])
        ]
    # One file (the template of the final estimator has at most a header):
    assert out.count('This file is generated by') <= 1
    if language != 'c':  # without classes
        for class_name in ('StandardScaler', 'StandardScaler2'):
            assert re.search(rf'\b{class_name}\b', out)
    # The steps are created and transform the features of each sample:
    assert re.search(r'step1\W*?\w*?transform', out, re.IGNORECASE)
    assert re.search(r'step2\W*?\w*?transform', out, re.IGNORECASE)
    for name in ('pipeline_classes', 'pipeline_create', 'pipeline_transform'):
        assert name not in out


@pytest.mark.parametrize('template', TEMPLATES)
@pytest.mark.parametrize('language', LANGUAGES)
def test_port_of_all_transformers(language: str, template: str):
    """Port a pipeline with all transformers to one file."""
    pipeline = _fit(
        [
            ('imputer', SimpleImputer()),
            ('min_max', MinMaxScaler(clip=True)),
            ('max_abs', MaxAbsScaler()),
            ('robust', RobustScaler()),
            ('standard', StandardScaler()),
            ('binarizer', Binarizer(threshold=0.5)),
            ('function', FunctionTransformer(np.log1p)),
            ('normalizer', Normalizer(norm='max')),
            ('k_bins', KBinsDiscretizer(n_bins=3, encode='ordinal')),
            ('ordinal', OrdinalEncoder()),
            ('clf', LogisticRegression(max_iter=1000)),
        ]
    )
    est = Pipeline(pipeline, language=language, template=template)
    out = est.port()
    if template == 'exported':
        out, data = out
        transformers = json.loads(data)['transformers']
        assert [sorted(t) for t in transformers] == [
            ['statistics'],
            ['min', 'scale'],
            ['scale'],
            ['center', 'scale'],
            ['mean', 'scale'],
            ['threshold'],
            [],
            [],
            ['edges', 'offsets'],
            ['categories', 'missing', 'offsets'],
        ]
    # No Jinja tags are left (two-dimensional arrays start with `{{`):
    assert '{%' not in out
    assert '{{ ' not in out
    if language != 'c':
        for name in ('SimpleImputer', 'MinMaxScaler', 'Binarizer'):
            assert name in out
    else:
        assert 'void step10_transform(' in out


@pytest.mark.parametrize('template', TEMPLATES)
@pytest.mark.parametrize('language', LANGUAGES)
def test_port_with_changing_number_of_features(language: str, template: str):
    """The transformers can change the number of features."""
    pipeline = _fit(
        [
            ('k_bins', KBinsDiscretizer(n_bins=3, encode='ordinal')),
            ('one_hot', OneHotEncoder(handle_unknown='ignore')),
            ('poly', PolynomialFeatures(2, interaction_only=True)),
            ('clf', LogisticRegression(max_iter=1000)),
        ]
    )
    est = Pipeline(pipeline, language=language, template=template)
    out = est.port()
    if template == 'exported':
        out, data = out
        transformers = json.loads(data)['transformers']
        assert [sorted(t) for t in transformers] == [
            ['edges', 'offsets'],
            ['categories', 'inputs', 'missing'],
            ['factors', 'offsets'],
        ]
    assert '{%' not in out
    assert '{{ ' not in out
    # The ported pipeline reads the features of the pipeline:
    assert 'You have to pass 4 features per sample.' in out or (
        language == 'c' and 'pipeline_read_features' in out
    )
    if language == 'c':
        assert 'double pipeline_values0[4];' in out
        assert 'double pipeline_values2[step2_N_FEATURES_OUT];' in out
        assert 'step3_transform(features, pipeline_values2);' in out
    elif language == 'cs':
        assert (
            'PipelineTransform = pipelineFeatures => step3.Transform('
            'step2.Transform(step1.Transform(pipelineFeatures)));'
        ) in out


